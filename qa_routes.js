const strip = s => s.replace(/[（(].*?[）)]/g, '');
// 鉄道駅 > バス停、完全一致 > 括弧除去一致 (index.html の findAllByName と同じ優先順位)
function idsOf(name) {
  const exact = [], loose = [];
  for (let i = 0; i < graph.stations.length; i++) {
    const n = graph.stations[i].n;
    if (n === name) exact.push(i);
    else if (strip(n) === strip(name)) loose.push(i);
  }
  const rail = a => a.filter(i => !graph.stations[i].m);
  for (const cand of [rail(exact), rail(loose), exact, loose]) if (cand.length) return cand;
  return [];
}
// 同名駅は index.html の doSearch と同じく総当たりして到着の早い順に採る
function journeysByName(fromName, toName, start) {
  const out = [], sigs = new Set();
  for (const s of idsOf(fromName)) {
    for (const g of idsOf(toName)) {
      if (s === g) continue;
      for (const j of R.findJourneys(s, g, start, {})) {
        const sig = `${j.dep}|${j.arr}|` + j.legs.map(l => l.kind === 'ride' ? l.line + l.dep : 'w').join('>');
        if (!sigs.has(sig)) { sigs.add(sig); out.push(j); }
      }
    }
  }
  out.sort((a, b) => (a.arr - b.arr) || (b.dep - a.dep) || (a.transfers - b.transfers));
  return out;
}
const nm = i => graph.stations[i].n;
const fmt = m => `${String(Math.floor(m / 60) % 24).padStart(2, '0')}:${String(m % 60).padStart(2, '0')}${m >= 1440 ? '+1' : ''}`;

function describe(j) {
  const fare = R.journeyFare(j);
  const km = R.journeyKm(j);
  const legs = j.legs.map(l => l.kind === 'walk' ? `徒歩${l.min}分`
    : `${l.line}${l.type ? '[' + l.type + ']' : ''} ${nm(l.from)}${fmt(l.dep)}→${nm(l.to)}${fmt(l.arr)}`);
  return { line: `${fmt(j.dep)}→${fmt(j.arr)} ${j.arr - j.dep}分 乗換${j.transfers} ${km.toFixed(1)}km ¥${fare.total}`, legs, km, fare: fare.total, dur: j.arr - j.dep, transfers: j.transfers };
}

