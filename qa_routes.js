function run(cases, kind) {
  const results = [];
  for (const c of cases) {
    const [from, to, at] = c;
    const expect = kind === 'minor' ? c[3] : null;
    const note = kind === 'minor' ? c[4] : c[3];
    const sc = idsOf(from), gc = idsOf(to);
    if (!sc.length || !gc.length) {
      results.push({ from, to, note, status: 'NO_STATION', detail: `${!sc.length ? from : ''}${!gc.length ? ' ' + to : ''} が駅リストに無い` });
      continue;
    }
    const t0 = Date.now();
    let js;
    try { js = journeysByName(from, to, at); }
    catch (e) { results.push({ from, to, note, status: 'ERROR', detail: e.message }); continue; }
    const ms = Date.now() - t0;
    if (!js || !js.length) { results.push({ from, to, note, status: 'NO_ROUTE', detail: `${ms}ms`, ms }); continue; }
    const d = describe(js[0]);
    let status = 'OK', detail = d.line;
    if (expect && (d.dur < expect[0] || d.dur > expect[1])) { status = 'RANGE'; detail = `${d.line}  [想定${expect[0]}-${expect[1]}分]`; }
    results.push({ from, to, note, status, detail, ms, legs: d.legs, dur: d.dur, km: d.km, transfers: d.transfers, fare: d.fare });
  }
  return results;
}

